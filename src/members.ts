export const getMembers = (...idsOrNames: string[]): Member[] => {
  return idsOrNames.map((idOrName) => {
    // IDで検索
    const byId = members.find((member) => member.id === idOrName);

    if (byId) {
      return byId;
    }

    // 名前で検索
    const byName = members.filter((member) => member.name === idOrName);

    if (byName.length === 1) {
      return byName[0];
    }

    if (byName.length > 1) {
      const ids = byName.map((member) => member.id).join(", ");

      throw new Error(
        `同名のメンバーが複数います: "${idOrName}" (${ids})。管理番号で指定してください。`
      );
    }

    throw new Error(`メンバーが見つかりません: "${idOrName}"`);
  });
};